#!/usr/bin/env node
// gen-tool-docs.mjs — regenerate docs/mcp-tools.md from the live tool list, so
// the reference never drifts from the code.   npm run docs:tools
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

process.env.TODOUZ_DATA_DIR ||= join(dirname(fileURLToPath(import.meta.url)), '..', 'demo-data');
const { TOOLS } = await import('../mcp-server/tools.mjs');

const GROUPS = [
  ['Folders & categories', /^(list_categories|create_category|delete_category|list_epics|get_epic|create_epic|update_epic|delete_epic|append_to_epic|list_epic_files|read_epic_file|write_epic_file|append_epic_file|delete_epic_file)$/],
  ['Items & checklists', /^(list_issues|get_issue|create_issue|create_subissue|update_issue|move_issue|complete_issue|delete_issue|list_completed|list_overdue|add_subtask|toggle_subtask|update_subtask|delete_subtask|write_note|attach_image|materialize_recurring)/],
  ['Schedule & calendar', /^(list_today|list_upcoming|add_timeblock|list_timeblocks|update_timeblock|complete_timeblock|delete_timeblock|add_event|list_events|update_event|delete_event)$/],
  ['Second brain', /^brain_/],
  ['Feed', /^(feed_|share_)/],
  ['Context, skills & sessions', /^(get_profile|get_full_context|list_skills|read_skill|write_skill|list_agents|list_sessions|link_session|update_session|delete_session)$/],
  ['Connectors & maintenance', /./],
];
const firstSentence = (d = '') => {
  const s = String(d).replace(/\s+/g, ' ').trim();
  const m = s.match(/^(.{20,240}?[.!?])(\s|$)/);
  return (m ? m[1] : s.slice(0, 240)).replace(/\|/g, '\\|');
};
const args = (t) => {
  const p = t.inputSchema?.properties || {}, req = new Set(t.inputSchema?.required || []);
  return Object.keys(p).map(k => req.has(k) ? `**${k}**` : k).join(', ') || '—';
};

const used = new Set();
let md = `# MCP tool reference\n\n_Generated by \`npm run docs:tools\` from \`mcp-server/\`. ${TOOLS.length} tools. **Bold** arguments are required._\n\n`;
md += 'Every tool is available three ways: over MCP (stdio, `mcp-server/index.mjs`), over HTTP as `POST /api/<tool_name>` with a JSON body, and to the in-app agent.\n\n';
for (const [title, re] of GROUPS) {
  const rows = TOOLS.filter(t => !used.has(t.name) && re.test(t.name));
  if (!rows.length) continue;
  rows.forEach(t => used.add(t.name));
  md += `## ${title}\n\n| Tool | What it does | Arguments |\n|---|---|---|\n`;
  for (const t of rows) md += `| \`${t.name}\` | ${firstSentence(t.description)} | ${args(t)} |\n`;
  md += '\n';
}
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'mcp-tools.md');
await writeFile(out, md);
console.log(`✓ wrote ${out} (${TOOLS.length} tools)`);
process.exit(0);
